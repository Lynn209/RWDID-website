(() => {
  "use strict";

  const EXPECTED_NAME = "cols4all::friendly13";
  const EXPECTED_VERSION = "0.11";
  const EXPECTED_COUNT = 13;

  function contrastText(hex) {
    const rgb = hex.replace("#", "").match(/.{2}/g).map(v => parseInt(v, 16) / 255);
    const linear = rgb.map(v => v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4));
    const luminance = 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2];
    const whiteContrast = 1.05 / (luminance + 0.05);
    const darkContrast = (luminance + 0.05) / 0.05;
    return darkContrast >= whiteContrast ? "#202735" : "#FFFFFF";
  }

  async function loadPalette() {
    const response = await fetch("data/friendly13_palette.json", { cache: "no-store" });
    if (!response.ok) {
      throw new Error("The calculator could not load its required colour palette. Please check the GitHub Pages deployment.");
    }

    const data = await response.json();
    if (data.palette !== EXPECTED_NAME) {
      throw new Error("Palette identity mismatch: expected cols4all::friendly13.");
    }
    if (String(data.package_version) !== EXPECTED_VERSION) {
      throw new Error(`Expected cols4all ${EXPECTED_VERSION}; found ${data.package_version || "unknown"}.`);
    }
    if (data.generated !== true || !Array.isArray(data.colors) ||
        data.colors.length !== EXPECTED_COUNT ||
        data.colors.some(c => typeof c !== "string" || !/^#[0-9A-Fa-f]{6}$/.test(c)) ||
        new Set(data.colors.map(c => c.toUpperCase())).size !== EXPECTED_COUNT) {
      throw new Error("The friendly13 palette must contain 13 unique HEX colors generated by cols4all.");
    }

    data.colors.forEach((color, i) => {
      const value = color.toUpperCase();
      document.documentElement.style.setProperty(`--friendly-${i + 1}`, value);
      document.documentElement.style.setProperty(`--friendly-${i + 1}-contrast`, contrastText(value));
    });

    document.documentElement.style.setProperty("--accent-main", data.colors[0].toUpperCase());
    document.documentElement.style.setProperty("--accent-main-contrast", contrastText(data.colors[0]));
    document.body.dataset.paletteReady = "true";

    const boot = document.getElementById("boot-state");
    const dynamicPage = document.querySelector("#app-shell, #methods-content");
    if (boot && dynamicPage && !dynamicPage.hidden) boot.hidden = true;

    document.querySelectorAll("[data-palette-status]").forEach(el => {
      el.textContent = `cols4all friendly13 · v${data.package_version}`;
    });

    const swatches = document.getElementById("friendly13-swatches");
    if (swatches) {
      swatches.innerHTML = data.colors.map((color, i) => `
        <div class="palette-swatch" title="friendly13 ${i + 1}: ${color}">
          <span style="background:${color}"></span>
          <small>${String(i + 1).padStart(2, "0")} · ${color.toUpperCase()}</small>
        </div>
      `).join("");
    }
    return data;
  }

  window.RWDIDPaletteReady = loadPalette();
  window.RWDIDPaletteReady.catch(error => {
    const boot = document.getElementById("boot-state");
    const app = document.getElementById("app-shell");
    if (app) app.hidden = true;
    if (boot) {
      boot.classList.add("boot-error");
      boot.innerHTML = `<strong>Website initialization could not be completed.</strong><p>${String(error.message).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]))}</p><p>Please contact the site maintainer if this message persists.</p>`;
    }
  });
})();
